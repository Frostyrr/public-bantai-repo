begin;

-- These alerts share the existing inbox. Preserve its recipient check and
-- remove access to old platform alerts when the recipient loses their role.
create policy platform_notifications_require_admin on public.notifications
  as restrictive for all to authenticated
  using (type not like 'platform.%' or (select public.is_platform_admin(false)))
  with check (type not like 'platform.%' or (select public.is_platform_admin(false)));

-- The standard workspace emitter must not spoof platform alerts or reserve their keys.
create or replace function public.emit_notifications(
  p_recipient_ids uuid[],
  p_organization_id uuid,
  p_type text,
  p_title text,
  p_message text,
  p_metadata jsonb default '{}'::jsonb,
  p_entity_type text default null,
  p_entity_id uuid default null,
  p_dedupe_prefix text default null
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_caller uuid := auth.uid();
  v_caller_role text;
  v_recipient uuid;
  v_inserted integer := 0;
  v_dedupe text;
begin
  if v_caller is null then
    raise exception 'Authentication required.' using errcode = '42501';
  end if;

  if not exists (
    select 1 from public.profiles p where p.id = v_caller and p.suspended_at is null
  ) then
    raise exception 'Active account required.' using errcode = '42501';
  end if;

  if trim(p_type) like 'platform.%' or trim(p_dedupe_prefix) like 'platform.%' then
    raise exception 'Platform alerts must be generated by trusted events.' using errcode = '42501';
  end if;

  if p_organization_id is not null then
    if not public.is_active_org_member(p_organization_id, v_caller) then
      raise exception 'Active organization membership is required.' using errcode = '42501';
    end if;

    select role into v_caller_role
    from public.organization_members
    where organization_id = p_organization_id
      and profile_id = v_caller
      and status = 'active';

    if p_type = 'organization.invitation_created' and v_caller_role not in ('owner', 'organization_admin') then
      raise exception 'Only owners and organization admins can emit invitation notifications.' using errcode = '42501';
    end if;
  end if;

  if p_recipient_ids is null or coalesce(array_length(p_recipient_ids, 1), 0) = 0 then
    return 0;
  end if;

  foreach v_recipient in array p_recipient_ids loop
    continue when v_recipient is null or v_recipient = v_caller;
    continue when not exists (select 1 from public.profiles where id = v_recipient);

    if p_organization_id is not null and p_type <> 'organization.invitation_created' then
      continue when not public.is_active_org_member(p_organization_id, v_recipient);
    end if;

    v_dedupe := case
      when p_dedupe_prefix is not null and length(trim(p_dedupe_prefix)) > 0
      then trim(p_dedupe_prefix) || ':' || v_recipient::text
      else null
    end;

    insert into public.notifications (
      recipient_user_id,
      organization_id,
      actor_user_id,
      type,
      title,
      message,
      metadata,
      entity_type,
      entity_id,
      dedupe_key
    )
    values (
      v_recipient,
      p_organization_id,
      v_caller,
      trim(p_type),
      left(trim(p_title), 200),
      left(trim(p_message), 1000),
      coalesce(p_metadata, '{}'::jsonb),
      p_entity_type,
      p_entity_id,
      v_dedupe
    )
    on conflict (dedupe_key) where dedupe_key is not null do nothing;

    if found then
      v_inserted := v_inserted + 1;
    end if;
  end loop;

  return v_inserted;
end;
$$;

create function public.emit_platform_inbox_alert(
  alert_type text, alert_title text, alert_message text, alert_key text,
  assigned_admin uuid, linked_incident uuid
)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.notifications (
    recipient_user_id, type, title, message, entity_type, entity_id, dedupe_key
  )
  select p.id, alert_type, alert_title, alert_message,
    case when linked_incident is not null then 'security_incident' end,
    linked_incident, alert_key || ':' || p.id::text
  from public.profiles p
  where p.suspended_at is null and (p.locked_until is null or p.locked_until <= statement_timestamp())
    and (
      (p.id = assigned_admin and p.role in ('admin', 'super_admin'))
      or (p.role = 'super_admin' and not exists (
        select 1 from public.profiles assignee
        where assignee.id = assigned_admin and assignee.role in ('admin', 'super_admin')
          and assignee.suspended_at is null
          and (assignee.locked_until is null or assignee.locked_until <= statement_timestamp())
      ))
    )
  on conflict (dedupe_key) where dedupe_key is not null do nothing;
exception when others then
  -- Alert delivery must not prevent security enforcement or incident creation.
  raise warning 'Platform inbox alert creation failed (SQLSTATE %)', sqlstate;
end;
$$;

create function public.notify_platform_security_incident()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  perform public.emit_platform_inbox_alert(
    'platform.incident_opened', 'Security incident needs review',
    case when new.severity = 'critical' then 'A critical security incident was opened.'
         else 'A high-severity security incident was opened.' end,
    'platform.incident:' || new.id::text, new.assigned_to, new.id
  );
  return new;
end;
$$;

create trigger platform_inbox_new_incident
after insert on public.security_incidents
for each row when (new.status = 'open' and new.severity in ('high', 'critical'))
execute function public.notify_platform_security_incident();

create function public.notify_platform_account_lock()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  perform public.emit_platform_inbox_alert(
    'platform.account_locked', 'Account temporarily locked',
    'A new account lock is available for review in Threat Detection.',
    'platform.account_lock:' || new.id::text || ':' ||
      to_char(statement_timestamp() at time zone 'UTC', 'YYYYMMDDHH'), null, null
  );
  return new;
end;
$$;

create trigger platform_inbox_new_account_lock
after update of locked_until on public.profiles
for each row when (new.locked_until > statement_timestamp()
  and (old.locked_until is null or old.locked_until <= statement_timestamp()))
execute function public.notify_platform_account_lock();

revoke all on function public.emit_platform_inbox_alert(text,text,text,text,uuid,uuid)
  from public, anon, authenticated, service_role;
revoke all on function public.notify_platform_security_incident() from public, anon, authenticated, service_role;
revoke all on function public.notify_platform_account_lock() from public, anon, authenticated, service_role;

commit;
